CREATE  TABLE T_LEVEL 
(
	DISTRICT VARCHAR(150),
	"Block/City" VARCHAR(150) ,
	"Gp/Ward" VARCHAR(150),
    VILLAGE VARCHAR(150),
    IS_RURAL VARCHAR(150),
    ENROLLMENT_DATE DATE,
	TOTAL_COUNT integer
);
 

INSERT INTO T_LEVEL
SELECT 
    DISTRICT,
    "Block/City",
    "Gp/Ward",
    VILLAGE,
    IS_RURAL,
    ENROLLMENT_DATE,
    COUNT(*) AS TOTAL_COUNT
FROM ENROLLMENT_DETAILED_DATA_COPY
GROUP BY ROLLUP (DISTRICT, "Block/City", "Gp/Ward", VILLAGE, IS_RURAL, ENROLLMENT_DATE);

