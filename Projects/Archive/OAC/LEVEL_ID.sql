CREATE TABLE LOCATION_HIERARCHY 
   (ROWID INTEGER, 
	DSHBRD_USER_NAME VARCHAR(50), 
	DSHBRD_ROLE_NAME VARCHAR(50)
	LEVELS NUMBER(*,0), 
	DISTRICT VARCHAR2(50 BYTE) COLLATE USING_NLS_COMP, 
	BLOCK_CITY VARCHAR2(50 BYTE) COLLATE USING_NLS_COMP, 
	GP_WARD VARCHAR2(50 BYTE) COLLATE USING_NLS_COMP, 
	VILLAGE VARCHAR2(50 BYTE) COLLATE USING_NLS_COMP, 
	USRNM VARCHAR2(50 BYTE) COLLATE USING_NLS_COMP, 
	APP_ROLE_NAME VARCHAR2(50 BYTE) COLLATE USING_NLS_COMP
   )  ;
 
 
INSERT INTO location_hierarchy (Levels, District, Block_City, Gp_Ward,Village)
SELECT 
    CASE 
        WHEN District IS NOT NULL AND "Block/City" IS NULL and "Gp/Ward" IS NULL AND Village IS NULL THEN 1
        WHEN District IS NOT NULL AND "Block/City" IS NOT NULL and "Gp/Ward" IS NULL AND Village IS NULL THEN 2
		WHEN District IS NOT NULL AND "Block/City" IS NOT NULL and "Gp/Ward" IS NOT NULL AND Village IS NULL THEN 3
        WHEN District IS NOT NULL AND "Block/City" IS NOT NULL and "Gp/Ward" IS NOT NULL AND Village IS NOT NULL THEN 4
    END AS Levels,
    District,
    "Block/City",
    "Gp/Ward",
	Village
FROM (
    SELECT DISTINCT District, "Block/City", "Gp/Ward", Village
    FROM T_LEVEL
)
ORDER BY District, "Block/City", "Gp/Ward", Village;